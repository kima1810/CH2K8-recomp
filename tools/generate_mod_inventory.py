"""Generate internal metadata from the Studio-hosted SDK inventory, not guest code."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
inventory=json.loads((root/'sdk/hooks.json').read_text())
ops=dict(before='CHMOD_OP_BEFORE',after='CHMOD_OP_AFTER',replace='CHMOD_OP_REPLACE',arguments='CHMOD_OP_ARGUMENTS',result='CHMOD_OP_RESULT',original='CHMOD_OP_ORIGINAL')
rows=[]
for h in inventory['package_hooks']:
    size=lambda x:'sizeof('+x+')' if x else '0'
    rows.append('{sizeof(ChmodHookInfo),'+str(h['numeric_id'])+','+str(h['version'])+','+'|'.join(ops[o] for o in h['operations'])+','+size(h['arguments'])+','+size(h['result'])+','+json.dumps(h['id'])+','+json.dumps(h['contract'])+'}')
(root/'port/src/mod_hook_inventory.inc').write_text('// Generated by tools/generate_mod_inventory.py from sdk/hooks.json\n'+',\n'.join(rows)+'\n')
